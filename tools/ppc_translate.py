#!/usr/bin/env python3
"""Any360's PowerPC translator: a title's functions, read from the PowerPC words of its XEX image, as C++.

Each function becomes `inline void sub_<address>(Ctx& ctx, const Memory& base)` on any360/xdk/ppc_model.h's context and
guest memory: one statement block per instruction, a label where a branch lands, the callees taken along. The
instructions covered (docs/CPU.md lists them with their encodings) are the most used ones of the known titles
(docs/ROADMAP.md); a function with any other instruction, a branch out of the function to anywhere but another
function's start, a jump table without a bound check, or a call to a function that cannot be translated, is left out. A
branch to another function's start is a tail call (the callee, then a return). A call or branch to one of the ABI's
register save and restore helpers (found by their code) becomes the helper of ppc_model.h. `bctrl` becomes
`ANY360_CPU_CALL_INDIRECT(ctx, base, target)`, which the code that includes the header defines: the title's function
table in a title, a recorded handler in the tests. The same for what needs the runtime: a call or branch to an import's
thunk (with --xex, which names the libraries) becomes `ANY360_CPU_CALL_IMPORT(ctx, base, <library>, <ordinal>)`, `mfmsr`
/ `mtmsrd` read and take or release the global lock (`ANY360_CPU_CHECK_GLOBAL_LOCK()`, `ANY360_CPU_ENTER_GLOBAL_LOCK()`,
`ANY360_CPU_LEAVE_GLOBAL_LOCK()`), `mftb` reads `ANY360_CPU_QUERY_TIMEBASE()`, and a trap whose condition holds calls
`ANY360_CPU_TRAP(ctx, base, <type>)`. `bctr` through a jump table (found from the words before it: the table's `lis` /
`addi`, its `lwzx`, `lhzx` or `lbzx`, the `add` of a base and the bound check `cmplwi` or `clrlwi` of the index) becomes
a `switch` on the index register with a label for each entry; any other `bctr`, and `bnectr`, a tail call through
ANY360_CPU_CALL_INDIRECT; `blrl` a call through it to lr.

  python -I tools/ppc_translate.py --image <default_image.bin> --functions <functions-<title>.json> \\
      [--xex <default.xex>] --namespace <ns> --out <header> (--root <address>... | --pick <count> [--min <instructions>]
      [--leaves])
  python -I tools/ppc_translate.py --cases <cases.txt> --namespace <ns> --out <header>

A cases file has one function a line: `<name> <hex word> <hex word> ...` (the words of a function that ends in blr), for
the instruction tests, each at 0x10000; a line `import <hex address> <library> <ordinal>` makes that address an import's
thunk for the cases; a line `@<hex address> <hex word> ...` puts data words there (a jump table), which the translator
reads and the header lists in kCaseData for the tests to write into guest memory.
"""
