#!/usr/bin/env python3
"""C++ from the titles' D3D device layouts (titles/<title>/d3d_layout.json, tools/d3d_layout_map.py).

    python tools/d3d_layout_header.py <title> --out <title repository>/src/d3d_layout.h
    python tools/d3d_layout_header.py --tests            (layer/xdk/tests/d3d_title_layouts.inc, every title)

The title's header defines the layout its binding passes to any360::host::rexglue::xdk::SetD3dLayout before its
first D3D call. A field the evidence did not read is 0xFFFFFFFF there: an offset no device holds, so that a native
reading it declines on its plain-memory check or fails loudly instead of using another runtime's value; the natives
that read such fields are not bound in the title.

The tests' file lists every title's layout for xdk_d3d_state_tests, which runs its layout-parameterized cases on each.
There an unread field keeps the default (the cases need some offset; the natives and their models read the same one).
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UNKNOWN = 0xFFFFFFFF


def load(title):
    return json.loads((ROOT / 'titles' / title / 'd3d_layout.json').read_text(encoding='utf-8'))


def assignments(data, unknown_value, indent):
    lines = [f'{indent}l.{field} = {entry["value"]}u;' for field, entry in data['fields'].items()]
    if unknown_value is not None:
        lines += [f'{indent}l.{field} = 0x{unknown_value:X}u;' for field in data['unknown']]
    return lines


def title_header(title):
    data = load(title)
    body = '\n'.join(assignments(data, UNKNOWN, '  '))
    unknown = ', '.join(data['unknown']) or 'none'
    return f'''// Generated by Any360's tools/d3d_layout_header.py from titles/{title}/d3d_layout.json: the D3D device layout of
// this title's runtime (any360::xdk::D3dLayout), each field read from the runtime's own code against the reference's
// (tools/d3d_layout_map.py). Unread fields (0xFFFFFFFF, no native that reads them is bound): {unknown}.
#pragma once

#include "any360/xdk/d3d_state.h"

namespace {title}_d3d {{

inline const any360::xdk::D3dLayout kLayout = [] {{
  any360::xdk::D3dLayout l;
{body}
  return l;
}}();

}}  // namespace {title}_d3d
'''


def tests_file():
    entries = []
    for path in sorted((ROOT / 'titles').glob('*/d3d_layout.json')):
        title = path.parent.name
        body = '\n'.join(assignments(load(title), None, '       '))
        entries.append(f'    {{"{title}", [] {{\n       xdk::D3dLayout l;\n{body}\n       return l;\n     }}()}},')
    return ('// Generated by tools/d3d_layout_header.py --tests from titles/*/d3d_layout.json: each title\'s D3D device '
            'layout,\n// its unread fields at the default (test data only: the cases and their models read the same '
            'offsets).\n' + '\n'.join(entries) + '\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('title', nargs='?')
    ap.add_argument('--out')
    ap.add_argument('--tests', action='store_true')
    args = ap.parse_args()
    if args.tests:
        out = ROOT / 'layer/xdk/tests/d3d_title_layouts.inc'
        out.write_bytes(tests_file().encode('utf-8'))
        print(f'wrote {out}')
    if args.title:
        Path(args.out).write_bytes(title_header(args.title).encode('utf-8'))
        print(f'wrote {args.out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
