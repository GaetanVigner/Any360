#!/usr/bin/env python3
"""Publishes the native D3D runtime's performance against the title's own (docs/D3D.md): the in-game self-test's report
(build-any360/d3d_selftest.txt, --any360_d3d_selftest=true) turned into docs/D3D_PERF.md, a table a case: the calls
compared, declined and different, each side's median time and the ratio, and each side's host heap allocations per
call (bytes and allocations, BenchmarkDotNet's "Allocated"), plus the in-game measures given with --note (frame rates
and lows, the functions the self-test cannot run). Run at the end of each step.

--archive <label> keeps the step's results: docs/perf/archive/<date>-<label>/ gets D3D_PERF.md, the raw self-test
report and the files given with --attach (A/B runs, tools/frame_lows.py outputs), and docs/perf/README.md lists it.

  python tools/d3d_perf.py crackdown <d3d_selftest.txt> [--note "text"]... [--out docs/D3D_PERF.md]
                           [--archive <label> [--attach <file>]...]
"""
import argparse
import re
import shutil
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LINE = re.compile(r'^(?P<name>.+?)\s+(?P<calls>\d+) calls, (?P<declined>\d+) declined, (?P<different>\d+) different; '
                  r'median original (?P<original>[\d.]+) ns, native (?P<native>[\d.]+) ns \((?P<ratio>[\d.]+)x faster\)'
                  r'(?:; allocated per call: original (?P<obytes>[\d.]+) B in (?P<ocount>[\d.]+), native '
                  r'(?P<nbytes>[\d.]+) B in (?P<ncount>[\d.]+))?')


def allocated(r, side):
    b, c = r[side + 'bytes'], r[side + 'count']
    return '-' if b is None else f'{float(b):.1f} B / {float(c):.3f}'


def main():
    p = argparse.ArgumentParser()
    p.add_argument('title')
    p.add_argument('report')
    p.add_argument('--note', action='append', default=[])
    p.add_argument('--out', default=str(ROOT / 'docs' / 'D3D_PERF.md'))
    p.add_argument('--archive', default='')
    p.add_argument('--attach', action='append', default=[])
    a = p.parse_args()
    rows = []
    for line in Path(a.report).read_text(encoding='utf-8').splitlines():
        m = LINE.match(line)
        if m:
            rows.append(m.groupdict())
    if not rows:
        raise SystemExit(f'no case in {a.report}')
    ratios = sorted(float(r['ratio']) for r in rows)
    different = sum(int(r['different']) for r in rows)
    metered = [r for r in rows if r['nbytes'] is not None]
    allocating = [r['name'] for r in metered if float(r['nbytes']) > 0]
    out = [
        '# Native D3D runtime against the title\'s',
        '',
        f'{a.title}, {date.today().isoformat()}: the in-game self-test (`--any360_d3d_selftest=true`, docs/D3D.md) runs '
        'each function the title\'s way and Any360\'s on the same random inputs, on a copy of the device, and compares '
        'every byte they write; the times are each side\'s median over 8 calls in a row, the allocations each side\'s '
        'host heap allocations per call (bytes / allocations; the title\'s guest heap is guest memory). Generated by '
        '`tools/d3d_perf.py` at the end of each step; earlier steps\' results are kept in `docs/perf/archive/`.',
        '',
        f'{len(rows)} cases, {different} calls different; Any360 {ratios[0]:.2f}x to {ratios[-1]:.2f}x the title\'s '
        f'speed (median {ratios[len(ratios) // 2]:.2f}x).' +
        (f' Allocations measured in {len(metered)} cases: ' +
         (f'{len(allocating)} allocate ({", ".join(allocating)}).' if allocating else 'none allocates.') if metered else ''),
        '',
    ]
    if a.note:
        out += ['In game:', ''] + [f'- {n}' for n in a.note] + ['']
    out += ['| Case | Calls | Declined | Different | Title (ns) | Any360 (ns) | Speed-up | Title allocated | Any360 allocated |',
            '|---|---:|---:|---:|---:|---:|---:|---:|---:|']
    for r in rows:
        out.append(f"| {r['name']} | {r['calls']} | {r['declined']} | {r['different']} | {float(r['original']):.1f} | "
                   f"{float(r['native']):.1f} | {float(r['ratio']):.2f}x | {allocated(r, 'o')} | {allocated(r, 'n')} |")
    text = '\n'.join(out) + '\n'
    with open(a.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(f'{len(rows)} cases, {different} different, {ratios[0]:.2f}x-{ratios[-1]:.2f}x; wrote {a.out}')
    if a.archive:
        folder = ROOT / 'docs' / 'perf' / 'archive' / f'{date.today().isoformat()}-{a.archive}'
        folder.mkdir(parents=True, exist_ok=True)
        with open(folder / 'D3D_PERF.md', 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        shutil.copyfile(a.report, folder / 'd3d_selftest.txt')
        for f in a.attach:
            shutil.copyfile(f, folder / Path(f).name)
        index = ROOT / 'docs' / 'perf' / 'README.md'
        head = ('# Performance archive\n\nEvery step\'s measured results, kept for later optimization passes: the '
                'self-test report (time and allocations per call against the title\'s), its published table, and the '
                'in-game A/B runs with their frame-time analysis (`tools/frame_lows.py`). Newest last.\n\n')
        lines = index.read_text(encoding='utf-8') if index.exists() else head
        entry = f'- [{folder.name}](archive/{folder.name}/): ' + '; '.join(n.split(':')[0] for n in a.note[:1]) + '\n'
        if f'(archive/{folder.name}/)' not in lines:
            lines += entry
        with open(index, 'w', encoding='utf-8', newline='\n') as f:
            f.write(lines)
        print(f'archived in {folder}')


if __name__ == '__main__':
    main()
