"""Turns a title's recompiled functions (ReXGlue's generated C++) into a reference model header for Any360's tests.

A function too long to transcribe by hand (an effect's whole chain of calls) is modelled by its own recompiled
statements, run on any360/xdk/ppc_model.h's context instead of the runtime's: the same operations in the same order,
so the native version written beside it can be tested against it off-game, bit for bit. Every function the root calls
is taken along (callees first). The asm comments stay, as the model's documentation.

With --native, the same statements are written as one leaf for the host: every function forced inline into the
root, the registers in a context local to the call (the compiler keeps them in host registers), memory reached
without the runtime's volatile accesses. The same operations in the same order, so the same bits; what it saves is the
recompiled code's traffic through the shared context. A header so made is a native function's first version, kept
only when the benchmark and the check in game say so (docs/NATIVE_FUNCTIONS.md).

usage: python -I tools/ppc_model.py [--native] <generated dir> <namespace> <out header> <root address> [...]
  e.g. python -I tools/ppc_model.py F:/Crackdown/crackdown-any360-sys/generated/default xaudio_reverb \\
           layer/xdk/include/any360/xdk/xaudio_reverb_reference.h 82A4DCF0
"""
import glob
import re
import sys
from pathlib import Path

HEADER = '''// Generated by tools/ppc_model.py from {title}'s recompiled code ({roots}): {what}.
// Do not edit by hand; run the tool again. Each function is the recompiled one's statements on
// any360/xdk/ppc_model.h's context: `ctx` the registers, `base` the guest memory.
#pragma once

#include "any360/xdk/ppc_model.h"

namespace {full_namespace} {{

using any360::xdk::Memory;
using any360::xdk::ppc_model::Ctx;
using any360::xdk::ppc_model::Reg;
using any360::xdk::ppc_model::VReg;
using any360::xdk::ppc_model::Load8;
using any360::xdk::ppc_model::Load16;
using any360::xdk::ppc_model::Load32;
using any360::xdk::ppc_model::Load64;
using any360::xdk::ppc_model::Store8;
using any360::xdk::ppc_model::Store16;
using any360::xdk::ppc_model::Store32;
using any360::xdk::ppc_model::Store64;
using any360::xdk::ppc_model::Raw;
using any360::xdk::ppc_model::SaveGprLr;
using any360::xdk::ppc_model::RestGprLr;
using any360::xdk::ppc_model::SaveFpr;
using any360::xdk::ppc_model::RestFpr;
using any360::xdk::ppc_model::VectorMaskL;
using any360::xdk::ppc_model::VectorMaskR;
using any360::xdk::ppc_model::ShuffleEpi8;
using any360::xdk::ppc_model::Vmaddfp;
using u8 = uint8_t;
using u16 = uint16_t;
using u32 = uint32_t;
using u64 = uint64_t;

'''

SUBSTITUTIONS = [
    (r'^(?:DEFINE_REX_FUNC|PPC_FUNC_IMPL)\((?:__imp__)?(sub_[0-9A-F]{8})\) \{', r'QUALIFIER void \1(Ctx& ctx, const Memory& base) {'),
    (r'^\s*REX_FUNC_PROLOGUE\(\);\n', ''),
    (r'\bPPCRegister temp\{\};', 'Reg temp{.u64 = 0};'),  # every byte, not only the union's first member
    (r'\bPPCRegister\b', 'Reg'),
    (r'\bREX_LOAD_U(8|16|32|64)\(', r'Load\1(base, '),
    (r'\bREX_STORE_U(8|16|32|64)\(', r'Store\1(base, '),
    (r'\bREX_RAW_ADDR\(', 'Raw(base, '),
    (r'(?:\brex::ppc::)?\bsimde_mm_vmaddfp\(', 'Vmaddfp('),
    (r'\bsimde_mm_shuffle_epi8\(', 'ShuffleEpi8('),
    (r'\bsimde__m128i\b', '__m128i'),
    (r'\bsimde__m128d\b', '__m128d'),
    (r'\bsimde__m128\b', '__m128'),
    (r'\bsimde_mm_', '_mm_'),
    (r'\b__(save|rest)gprlr_(\d+)\(ctx, base\)', lambda m: '%sGprLr(ctx, base, %s)' % (m.group(1).capitalize(), m.group(2))),
    (r'\b__(save|rest)fpr_(\d+)\(ctx, base\)', lambda m: '%sFpr(ctx, base, %s)' % (m.group(1).capitalize(), m.group(2))),
]
UNSUPPORTED = re.compile(r'\b(REX_MM_|PPC_CALL_INDIRECT|ctx\.ctr|__imp__|rex::(?!ppc::simde_mm_vmaddfp)|REX_LOAD_STRING|simde_mm_v(?!maddfp))')


def functions(generated):
    found = {}
    for path in sorted(glob.glob(str(Path(generated) / '*_recomp.*.cpp'))):
        lines = Path(path).read_text(encoding='utf-8', errors='replace').splitlines(keepends=True)
        i = 0
        while i < len(lines):
            m = re.match(r'(?:DEFINE_REX_FUNC|PPC_FUNC_IMPL)\((?:__imp__)?sub_([0-9A-F]{8})\)', lines[i])
            if m:
                j = i + 1
                while j < len(lines) and not lines[j].startswith('}'):
                    j += 1
                found[m.group(1)] = ''.join(lines[i:j + 1])
                i = j
            i += 1
    return found


def main():
    args = sys.argv[1:]
    native = args[:1] == ['--native']
    if native:
        args = args[1:]
    generated, namespace, out, *roots = args
    qualifier = '[[gnu::always_inline]] inline' if native else 'inline'
    full_namespace = ('any360::xdk::detail::%s_native' if native else 'any360::xdk::reference::%s') % namespace
    what = ('the native leaf of %s (every function inlined, registers local)' if native else
            'the reference model of %s') % namespace
    roots = [r.upper() for r in roots]
    found = functions(generated)
    order, seen = [], set()

    def walk(address):
        if address in seen:
            return
        if address not in found:
            sys.exit('sub_%s: not in the generated code' % address)
        seen.add(address)
        for callee in re.findall(r'\bsub_([0-9A-F]{8})\(ctx, base\)', found[address]):
            if callee != address:
                walk(callee)
        order.append(address)

    for root in roots:
        walk(root)
    title = Path(generated).resolve().parent.parent.name
    text = HEADER.format(title=title, roots=', '.join('sub_' + r for r in roots), what=what,
                         full_namespace=full_namespace)
    text += ''.join('%s void sub_%s(Ctx& ctx, const Memory& base);\n' % (qualifier, a) for a in order) + '\n'
    for address in order:
        body = found[address]
        for line in body.splitlines():
            if not line.strip().startswith('//') and UNSUPPORTED.search(line):
                sys.exit('sub_%s: not supported yet: %s' % (address, line.strip()))
        for pattern, replacement in SUBSTITUTIONS:
            body = re.sub(pattern, replacement, body, flags=re.M)
        body = body.replace('QUALIFIER', qualifier, 1)
        text += body + '\n'
    text += '}  // namespace %s\n' % full_namespace
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('%s: %d functions (%s), %d lines' % (out, len(order), ' '.join(order), text.count('\n')))


if __name__ == '__main__':
    main()
