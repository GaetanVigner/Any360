#!/usr/bin/env python3
"""Sorts the system calls Any360 does not answer itself (db/system_calls.json, `any360` != native) by what is known
about them, for step 12 of docs/SYS_BINDING.md.

The reference runtime stubs them (it never needed them) and no known title imports them, so nothing in the titles
says what they must do. The sort takes its evidence from Xenia Canary's kernel sources (the emulator the reference
descends from, which runs many more titles), read for the names and tags of its export declarations only:

- `implement`: Xenia implements it (`kImplemented`): a title it runs calls it and it does work there; its source is
  a starting point for an Any360 version with scenario tests;
- `retail-stub`: Xenia declares it as a stub too (`kStub`), or marks it doubtful (`kSketchy`): titles it runs call it
  and a stub's answer is what they live with; the reference's stub answer stays until a title shows otherwise;
- `debug-only`: xbdm.dll, the debug monitor, which a retail console does not load;
- `never-seen`: in neither: no title Xenia runs is known to call it; the first call logs (`any360_sys_trace`).

  python -I tools/sys_stub_sort.py --xenia F:/Sources/xenia-canary [--out-json db/sys_stub_sort.json]
      [--out-md docs/SYS_STUBS.md]

Only export names, groups and counts are written. Standard library only.
"""
import argparse
import json
import re
import subprocess
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DECLARATION = re.compile(r'DECLARE_(?:XAM|XBOXKRNL|XBDM)_EXPORT\d\(\s*(\w+)\s*,\s*\w+\s*((?:,\s*\w+\s*)*)\)')
BUCKETS = ('implement', 'retail-stub', 'debug-only', 'never-seen')


def xenia_tags(xenia):
    tags = {}
    for path in (xenia / 'src' / 'xenia' / 'kernel').rglob('*.cc'):
        for name, rest in DECLARATION.findall(path.read_text(encoding='utf-8', errors='replace')):
            tags[name] = [t.strip() for t in rest.split(',') if t.strip()]
    return tags


def xenia_commit(xenia):
    try:
        return subprocess.run(['git', '-C', str(xenia), 'rev-parse', '--short', 'HEAD'], capture_output=True,
                              text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return 'unknown'


def bucket(row, tags):
    if row['library'] == 'xbdm':
        return 'debug-only'
    t = tags.get(row['name'])
    if t is None:
        return 'never-seen'
    return 'implement' if 'kImplemented' in t else 'retail-stub'


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--xenia', type=Path, required=True, help='a Xenia Canary source checkout')
    parser.add_argument('--db', type=Path, default=ROOT / 'db' / 'system_calls.json')
    parser.add_argument('--out-json', type=Path, default=ROOT / 'db' / 'sys_stub_sort.json')
    parser.add_argument('--out-md', type=Path, default=ROOT / 'docs' / 'SYS_STUBS.md')
    args = parser.parse_args()

    rows = json.loads(args.db.read_text(encoding='utf-8'))
    tags = xenia_tags(args.xenia)
    commit = xenia_commit(args.xenia)
    stubs = sorted((r for r in rows if r['any360'] != 'native' and r['kind'] == 'function'),
                   key=lambda r: (r['library'], r['group'], r['name']))
    sorted_rows = [{'name': r['name'], 'library': r['library'], 'group': r['group'], 'bucket': bucket(r, tags),
                    'xenia': tags.get(r['name'], [])} for r in stubs]

    lines = ',\n'.join(json.dumps(r, separators=(',', ':')) for r in sorted_rows)
    args.out_json.write_text(f'{{"xenia":"{commit}","exports":[\n{lines}\n]}}\n', encoding='utf-8')

    counts = Counter(r['bucket'] for r in sorted_rows)
    # The known titles (those whose imports are in the database) and how many of the sorted calls they import.
    known = sorted({t for r in rows for t in r.get('titles', [])})
    imported = sum(1 for r in stubs if r.get('titles'))
    by_group = defaultdict(Counter)
    for r in sorted_rows:
        by_group[r['group']][r['bucket']] += 1
    md = ['# System calls Any360 does not answer itself, sorted', '',
          f'Generated by `tools/sys_stub_sort.py` from `db/system_calls.json` and Xenia Canary\'s kernel sources (commit '
          f'{commit}): step 12 of [SYS_BINDING.md](SYS_BINDING.md). The reference runtime stubs every one of them and no '
          'known title imports them; the evidence for each is whether Xenia, which runs many more titles, implements '
          'it, stubs it too, or does not know it.', '',
          f'{len(sorted_rows)} functions: **{counts["implement"]} to implement** (Xenia implements them), '
          f'**{counts["retail-stub"]} answered as a stub** (Xenia stubs them too or marks them doubtful), '
          f'**{counts["debug-only"]} debug only** (xbdm, absent on a retail console), '
          f'**{counts["never-seen"]} never seen** (no title Xenia runs is known to call them).', '',
          f'The {len(known)} known titles ({", ".join(known)}) import {imported} of these {len(sorted_rows)}: every '
          'call they import is answered natively.' if not imported else
          f'The {len(known)} known titles ({", ".join(known)}) import {imported} of these {len(sorted_rows)}.', '',
          '| Group | ' + ' | '.join(BUCKETS) + ' |', '|---|' + '---:|' * len(BUCKETS)]
    for group in sorted(by_group, key=lambda g: -sum(by_group[g].values())):
        md.append(f'| {group} | ' + ' | '.join(str(by_group[group][b] or '') for b in BUCKETS) + ' |')
    md += ['', '## To implement', '', 'Each needs a stated source for its answer (Xenia\'s code, the XDK\'s '
           'documentation, a standard\'s test vectors) and scenario tests before it is bound.', '']
    for group in sorted({r['group'] for r in sorted_rows if r['bucket'] == 'implement'}):
        names = [r['name'] for r in sorted_rows if r['bucket'] == 'implement' and r['group'] == group]
        md.append(f'- **{group}** ({len(names)}): ' + ', '.join(f'`{n}`' for n in names))
    args.out_md.write_text('\n'.join(md) + '\n', encoding='utf-8')
    print(f'{len(sorted_rows)} sorted: ' + ', '.join(f'{b} {counts[b]}' for b in BUCKETS) + f' (Xenia {commit})')


if __name__ == '__main__':
    main()
