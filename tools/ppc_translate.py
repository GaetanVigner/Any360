class Unsupported(Exception):
    pass


def s16(v):
    return v - 0x10000 if v & 0x8000 else v


def s14(v):
    v &= 0xFFFC
    return v - 0x10000 if v & 0x8000 else v


def s26(v):
    v &= 0x3FFFFFC
    return v - 0x4000000 if v & 0x2000000 else v


def mask64(mb, me):
    """The PowerPC mask of bits mb..me (bit 0 the most significant of 64), wrapping when mb > me."""
    def ones_from(b):
        return (1 << (64 - b)) - 1
    if mb <= me:
        return ones_from(mb) & ~ones_from(me + 1) & 0xFFFFFFFFFFFFFFFF
    return (ones_from(mb) | (~ones_from(me + 1) & 0xFFFFFFFFFFFFFFFF)) & 0xFFFFFFFFFFFFFFFF


CR_BITS = ('lt', 'gt', 'eq', 'so')


def ea(ra, d):
    return f'{d}u' if ra == 0 else f'ctx.r{ra}.u32 + {d}u' if d >= 0 else f'ctx.r{ra}.u32 - {-d}u'


def cr0(reg):
    return f'ctx.cr0.compare<int32_t>(ctx.r{reg}.s32, 0, ctx.xer);'


def eax(ra, rb):
    return f'ctx.r{rb}.u32' if ra == 0 else f'ctx.r{ra}.u32 + ctx.r{rb}.u32'


LOADS = {34: 'Load8', 40: 'Load16'}
STORES = {38: ('Store8', 'u8'), 44: ('Store16', 'u16')}
X_LOADS = {23: 'Load32', 87: 'Load8', 279: 'Load16'}
X_STORES = {151: ('Store32', 'u32'), 215: ('Store8', 'u8'), 407: ('Store16', 'u16')}
X_LOGICAL = {28: '{s} & {b}', 60: '{s} & ~{b}', 316: '{s} ^ {b}', 124: '~({s} | {b})'}
EXTEND = {922: 's16', 954: 's8', 986: 's32'}
SINGLE = {18: '/', 20: '-', 21: '+'}
DOUBLE = {18: '/', 20: '-', 21: '+'}


def trap(to, a_signed, a_unsigned, b_signed, b_unsigned):
    """A trap's statements: ANY360_CPU_TRAP(ctx, base, 0) under the TO field's conditions (signed <, >, ==, unsigned
    <, >), none for TO 0, unconditional for TO 31."""
    if to == 0:
        return []
    if to == 31:
        return ['ANY360_CPU_TRAP(ctx, base, 0);']
    terms = [f'{a} {op} {b}' for bit, a, op, b in (
        (16, a_signed, '<', b_signed), (8, a_signed, '>', b_signed), (4, a_signed, '==', b_signed),
        (2, a_unsigned, '<', b_unsigned), (1, a_unsigned, '>', b_unsigned)) if to & bit]
    return [f'if ({" || ".join(terms)}) ANY360_CPU_TRAP(ctx, base, 0);']


class Instruction:
    def __init__(self, address, word):
        self.address, self.word = address, word
        self.target = None      # a branch's target inside or outside the function
        self.call = False       # bl
        self.indirect = False   # bctrl: a call through the count register
        self.ends = False       # blr, b, or a branch with no fall-through
        self.fpu = False        # a floating-point instruction that runs with the flush mode off
        self.table = None       # bctr through a jump table: its targets, entry by entry
        self.code = self.decode()

    def decode(self):
        w, a = self.word, self.address
        op = w >> 26
        rd, ra, rb = (w >> 21) & 31, (w >> 16) & 31, (w >> 11) & 31
        imm = w & 0xFFFF
        rc = w & 1
        if op == 14:
            return [f'ctx.r{rd}.s64 = {s16(imm)};' if ra == 0 else f'ctx.r{rd}.s64 = ctx.r{ra}.s64 + {s16(imm)};']
        if op == 15:
            shifted = s16(imm) << 16
            return [f'ctx.r{rd}.s64 = {shifted}ll;' if ra == 0 else f'ctx.r{rd}.s64 = ctx.r{ra}.s64 + {shifted}ll;']
        if op == 32:
            return [f'ctx.r{rd}.u64 = Load32(base, {ea(ra, s16(imm))});']
        if op == 36:
            return [f'Store32(base, {ea(ra, s16(imm))}, ctx.r{rd}.u32);']
        if op == 37:
            if ra == 0:
                raise Unsupported('stwu with rA 0')
            return [f'ea = {ea(ra, s16(imm))};', f'Store32(base, ea, ctx.r{rd}.u32);', f'ctx.r{ra}.u32 = ea;']
        if op == 58 and w & 3 == 0:
            return [f'ctx.r{rd}.u64 = Load64(base, {ea(ra, s14(imm))});']
        if op == 62 and w & 3 == 0:
            return [f'Store64(base, {ea(ra, s14(imm))}, ctx.r{rd}.u64);']
        if op in LOADS:
            return [f'ctx.r{rd}.u64 = {LOADS[op]}(base, {ea(ra, s16(imm))});']
        if op in STORES:
            name, field = STORES[op]
            return [f'{name}(base, {ea(ra, s16(imm))}, ctx.r{rd}.{field});']
        if op == 48:
            self.fpu = True
            return [f'ctx.f{rd}.f64 = double(std::bit_cast<float>(Load32(base, {ea(ra, s16(imm))})));']
        if op == 50:
            self.fpu = True
            return [f'ctx.f{rd}.u64 = Load64(base, {ea(ra, s16(imm))});']
        if op == 52:
            self.fpu = True
            return [f'Store32(base, {ea(ra, s16(imm))}, std::bit_cast<uint32_t>(float(ctx.f{rd}.f64)));']
        if op == 54:
            self.fpu = True
            return [f'Store64(base, {ea(ra, s16(imm))}, ctx.f{rd}.u64);']
        if op == 24:
            if rd == ra == 0 and imm == 0:
                return []
            return [f'ctx.r{ra}.u64 = ctx.r{rd}.u64 | {imm};']
        if op == 25:
            return [f'ctx.r{ra}.u64 = ctx.r{rd}.u64 | {imm << 16};']
        if op == 26:
            return [f'ctx.r{ra}.u64 = ctx.r{rd}.u64 ^ {imm};']
        if op == 28:
            return [f'ctx.r{ra}.u64 = ctx.r{rd}.u64 & {imm};', cr0(ra)]
        if op == 7:
            return [f'ctx.r{rd}.s64 = static_cast<int64_t>(ctx.r{ra}.u64 * static_cast<uint64_t>({s16(imm)}ll));']
        if op == 8:
            k = s16(imm)
            return [f'ctx.xer.ca = ctx.r{ra}.u32 <= {k & 0xFFFFFFFF}u;',
                    f'ctx.r{rd}.u64 = static_cast<uint64_t>({k}ll) - ctx.r{ra}.u64;']
        if op in (12, 13):
            k = s16(imm)
            return [f'ctx.xer.ca = ctx.r{ra}.u32 > {~k & 0xFFFFFFFF}u;',
                    f'ctx.r{rd}.s64 = ctx.r{ra}.s64 + {k};'] + ([cr0(rd)] if op == 13 else [])
        if op == 20:
            sh, mb, me = rb, (w >> 6) & 31, (w >> 1) & 31
            m = mask64(mb + 32, me + 32)
            return [f'ctx.r{ra}.u64 = (std::rotl(uint64_t(ctx.r{rd}.u32) | (uint64_t(ctx.r{rd}.u32) << 32), {sh}) & '
                    f'0x{m:X}ull) | (ctx.r{ra}.u64 & 0x{~m & 0xFFFFFFFFFFFFFFFF:X}ull);'] + ([cr0(ra)] if rc else [])
        if op == 30 and (w >> 2) & 7 in (0, 1, 3):
            xo = (w >> 2) & 7
            sh = rb | (((w >> 1) & 1) << 5)
            field = (w >> 5) & 0x3F
            m6 = ((field & 1) << 5) | (field >> 1)
            m = mask64(m6, 63) if xo == 0 else mask64(0, m6) if xo == 1 else mask64(m6, 63 - sh)
            rot = f'std::rotl(ctx.r{rd}.u64, {sh})' if sh else f'ctx.r{rd}.u64'
            if xo == 3:
                code = f'ctx.r{ra}.u64 = ({rot} & 0x{m:X}ull) | (ctx.r{ra}.u64 & 0x{~m & 0xFFFFFFFFFFFFFFFF:X}ull);'
            else:
                code = f'ctx.r{ra}.u64 = {rot} & 0x{m:X}ull;'
            return [code] + ([cr0(ra)] if rc else [])
        if op == 59 and not rc:
            xo, frc = (w >> 1) & 31, (w >> 6) & 31
            self.fpu = True
            if xo in SINGLE and frc == 0:
                return [f'ctx.f{rd}.f64 = double(float(ctx.f{ra}.f64 {SINGLE[xo]} ctx.f{rb}.f64));']
            if xo == 25 and rb == 0:
                return [f'ctx.f{rd}.f64 = double(float(ctx.f{ra}.f64 * ctx.f{frc}.f64));']
            if xo in (28, 29, 30):
                return [f'ctx.f{rd}.f64 = double(float({self.fused(xo, ra, frc, rb)}));']
            raise Unsupported(f'opcode 59 xo {xo}')
        if op == 63 and not rc:
            xo, frc = (w >> 1) & 0x3FF, (w >> 6) & 31
            self.fpu = True
            if xo == 0 and not (w >> 21) & 3:
                return [f'ctx.cr{(w >> 23) & 7}.compare(ctx.f{ra}.f64, ctx.f{rb}.f64);']
            if xo == 12 and ra == 0:
                return [f'ctx.f{rd}.f64 = double(float(ctx.f{rb}.f64));']
            if xo == 72 and ra == 0:
                return [f'ctx.f{rd}.f64 = ctx.f{rb}.f64;']
            if xo == 40 and ra == 0:
                return [f'ctx.f{rd}.u64 = ctx.f{rb}.u64 ^ 0x8000000000000000ull;']
            if xo == 264 and ra == 0:
                return [f'ctx.f{rd}.u64 = ctx.f{rb}.u64 & ~0x8000000000000000ull;']
            xo5 = xo & 31
            if xo5 in DOUBLE and frc == 0:
                return [f'ctx.f{rd}.f64 = ctx.f{ra}.f64 {DOUBLE[xo5]} ctx.f{rb}.f64;']
            if xo5 == 25 and rb == 0:
                return [f'ctx.f{rd}.f64 = ctx.f{ra}.f64 * ctx.f{frc}.f64;']
            if xo5 in (28, 29):
                return [f'ctx.f{rd}.f64 = {self.fused(xo5, ra, frc, rb)};']
            raise Unsupported(f'opcode 63 xo {xo}')
        if op in (10, 11):
            crf, wide = (w >> 23) & 7, (w >> 21) & 1
            if op == 11:
                t, v, k = ('int64_t', f'ctx.r{ra}.s64', s16(imm)) if wide else ('int32_t', f'ctx.r{ra}.s32', s16(imm))
            else:
                t, v, k = ('uint64_t', f'ctx.r{ra}.u64', imm) if wide else ('uint32_t', f'ctx.r{ra}.u32', imm)
            return [f'ctx.cr{crf}.compare<{t}>({v}, {k}, ctx.xer);']
        if op == 21:
            sh, mb, me = rb, (w >> 6) & 31, (w >> 1) & 31
            m = mask64(mb + 32, me + 32)
            rot = (f'std::rotl(uint64_t(ctx.r{rd}.u32) | (uint64_t(ctx.r{rd}.u32) << 32), {sh})' if sh
                   else f'(uint64_t(ctx.r{rd}.u32) | (uint64_t(ctx.r{rd}.u32) << 32))')
            return [f'ctx.r{ra}.u64 = {rot} & 0x{m:X}ull;'] + ([cr0(ra)] if rc else [])
        if op == 3:
            to, k = rd, s16(imm)
            if to == 31 and ra == 0:
                return [f'ANY360_CPU_TRAP(ctx, base, {k & 0xFFFF});']
            return trap(to, f'ctx.r{ra}.s32', f'ctx.r{ra}.u32', f'{k}', f'{k & 0xFFFFFFFF}u')
        if op == 2:
            k = s16(imm)
            return trap(rd, f'ctx.r{ra}.s64', f'ctx.r{ra}.u64', f'{k}ll', f'{k & 0xFFFFFFFFFFFFFFFF}ull')
        if op == 31:
            xo = (w >> 1) & 0x3FF
            if xo in (4, 68):
                wide = 64 if xo == 68 else 32
                return trap(rd, f'ctx.r{ra}.s{wide}', f'ctx.r{ra}.u{wide}', f'ctx.r{rb}.s{wide}', f'ctx.r{rb}.u{wide}')
            if xo == 83 and not ra and not rb:
                return ['std::atomic_thread_fence(std::memory_order_seq_cst);',
                        f'ctx.r{rd}.u64 = ANY360_CPU_CHECK_GLOBAL_LOCK();']
            if xo == 178 and ra == 1 and not rb:
                return ['std::atomic_thread_fence(std::memory_order_seq_cst);',
                        f'ctx.msr = (ctx.r{rd}.u32 & 0x8020) | (ctx.msr & ~0x8020);',
                        'ANY360_CPU_ENTER_GLOBAL_LOCK();' if rd == 13 else 'ANY360_CPU_LEAVE_GLOBAL_LOCK();']
            if xo == 371:
                tbr = ra | (rb << 5)
                if tbr not in (268, 269):
                    raise Unsupported(f'mftb {tbr}')
                return [f'ctx.r{rd}.u64 = ANY360_CPU_QUERY_TIMEBASE(){" >> 32" if tbr == 269 else ""};']
            if xo in (0, 32):
                crf, wide = (w >> 23) & 7, (w >> 21) & 1
                kind = 's' if xo == 0 else 'u'
                t = {('s', 0): 'int32_t', ('s', 1): 'int64_t', ('u', 0): 'uint32_t', ('u', 1): 'uint64_t'}[(kind, wide)]
                field = f'{kind}{64 if wide else 32}'
                return [f'ctx.cr{crf}.compare<{t}>(ctx.r{ra}.{field}, ctx.r{rb}.{field}, ctx.xer);']
            if xo in X_LOADS:
                return [f'ctx.r{rd}.u64 = {X_LOADS[xo]}(base, {eax(ra, rb)});']
            if xo in X_STORES:
                name, field = X_STORES[xo]
                return [f'{name}(base, {eax(ra, rb)}, ctx.r{rd}.{field});']
            if xo == 535:
                self.fpu = True
                return [f'ctx.f{rd}.f64 = double(std::bit_cast<float>(Load32(base, {eax(ra, rb)})));']
            if xo == 663:
                self.fpu = True
                return [f'Store32(base, {eax(ra, rb)}, std::bit_cast<uint32_t>(float(ctx.f{rd}.f64)));']
            record = [cr0(ra)] if rc else []
            if xo in X_LOGICAL:
                value = X_LOGICAL[xo].format(s=f'ctx.r{rd}.u64', b=f'ctx.r{rb}.u64')
                return [f'ctx.r{ra}.u64 = {value};'] + record
            if xo in EXTEND and rb == 0:
                return [f'ctx.r{ra}.s64 = ctx.r{rd}.{EXTEND[xo]};'] + record
            if xo == 26 and rb == 0:
                return [f'ctx.r{ra}.u64 = std::countl_zero(ctx.r{rd}.u32);'] + record
            if xo in (24, 536):
                shift = '<<' if xo == 24 else '>>'
                return [f'ctx.r{ra}.u64 = ctx.r{rb}.u8 & 0x20 ? 0 : (ctx.r{rd}.u32 {shift} (ctx.r{rb}.u8 & 0x1F));'] + record
            if xo == 824:
                if rb == 0:
                    return ['ctx.xer.ca = 0;', f'ctx.r{ra}.s64 = ctx.r{rd}.s32;'] + record
                return [f'ctx.xer.ca = (ctx.r{rd}.s32 < 0) & ((ctx.r{rd}.u32 & 0x{(1 << rb) - 1:X}u) != 0);',
                        f'ctx.r{ra}.s64 = ctx.r{rd}.s32 >> {rb};'] + record
            if xo in (86, 278, 598, 854) and not rc:
                return []
            arithmetic = [cr0(rd)] if rc else []
            if xo == 202 and rb == 0:
                return [f'{{ const uint32_t addend = ctx.r{ra}.u32;', f'ctx.r{rd}.u64 = ctx.r{ra}.u64 + ctx.xer.ca;',
                        f'ctx.xer.ca = ctx.r{rd}.u32 < addend; }}'] + arithmetic
            if xo == 40:
                return [f'ctx.r{rd}.u64 = ctx.r{rb}.u64 - ctx.r{ra}.u64;'] + arithmetic
            if xo == 235:
                return [f'ctx.r{rd}.s64 = int64_t(ctx.r{ra}.s32) * int64_t(ctx.r{rb}.s32);'] + arithmetic
            if xo == 104 and rb == 0:
                return [f'ctx.r{rd}.s64 = static_cast<int64_t>(-ctx.r{ra}.u64);'] + arithmetic
            if xo == 444:
                value = f'ctx.r{rd}.u64' if rd == rb else f'ctx.r{rd}.u64 | ctx.r{rb}.u64'
                return [f'ctx.r{ra}.u64 = {value};'] + ([cr0(ra)] if rc else [])
            if xo == 266 and not (w >> 10) & 1:
                return [f'ctx.r{rd}.u64 = ctx.r{ra}.u64 + ctx.r{rb}.u64;'] + ([cr0(rd)] if rc else [])
            if xo in (339, 467):
                spr = ((w >> 16) & 31) | (((w >> 11) & 31) << 5)
                name = {8: 'lr', 9: 'ctr'}.get(spr)
                if not name:
                    raise Unsupported(f'spr {spr}')
                register = 'ctx.lr' if name == 'lr' else 'ctx.ctr.u64'
                return [f'ctx.r{rd}.u64 = {register};' if xo == 339 else f'{register} = ctx.r{rd}.u64;']
            raise Unsupported(f'opcode 31 xo {xo}')
        if op == 18:
            target = (s26(w) if w & 2 else a + s26(w)) & 0xFFFFFFFF
            self.target = target
            if w & 1:
                self.call = True
                return [f'ctx.lr = 0x{a + 4:X};', f'sub_{target:08X}(ctx, base);']
            self.ends = True
            return [f'goto loc_{target:08X};']
        if op == 16:
            bo, bi = rd, ra
            if w & 3:
                raise Unsupported('bc with link or absolute')
            target = (a + s14(w)) & 0xFFFFFFFF
            self.target = target
            decrement, condition = self.condition(bo, bi)
            if condition is None:
                self.ends = True
                return [f'goto loc_{target:08X};']
            return decrement + [f'if ({condition}) goto loc_{target:08X};']
        if w == 0x4E800421:
            self.indirect = True
            return [f'ctx.lr = 0x{a + 4:X};', 'ANY360_CPU_CALL_INDIRECT(ctx, base, ctx.ctr.u32);']
        if w == BCTR:
            self.ends = True
            return ['ANY360_CPU_CALL_INDIRECT(ctx, base, ctx.ctr.u32);', 'return;']
        if op == 19 and (w >> 1) & 0x3FF == 528 and not w & 1 and rd & 0x4:
            _, condition = self.condition(rd, ra)
            if condition is None:
                raise Unsupported('bcctr with BO 20 other than bctr')
            return [f'if ({condition}) {{ ANY360_CPU_CALL_INDIRECT(ctx, base, ctx.ctr.u32); return; }}']
        if w == 0x4E800021:
            self.indirect = True
            return ['{ const uint32_t target = uint32_t(ctx.lr);', f'ctx.lr = 0x{a + 4:X};',
                    'ANY360_CPU_CALL_INDIRECT(ctx, base, target); }']
        if op == 19 and (w >> 1) & 0x3FF == 16 and not w & 1:
            decrement, condition = self.condition(rd, ra)
            if condition is None:
                self.ends = True
                return ['return;']
            return decrement + [f'if ({condition}) return;']
        raise Unsupported(f'opcode {op}')

    def set_table(self, index, targets):
        self.table = targets
        self.code = [f'switch (ctx.r{index}.u32) {{']
        self.code += [f'case {n}: goto loc_{target:08X};' for n, target in enumerate(targets)]
        self.code += ['default: __builtin_trap();', '}']

    @staticmethod
    def fused(xo, ra, frc, rb):
        """frA * frC + frB (xo 29), frA * frC - frB (28), -(frA * frC - frB) (30), the product and sum rounded once."""
        if xo == 29:
            return f'std::fma(ctx.f{ra}.f64, ctx.f{frc}.f64, ctx.f{rb}.f64)'
        difference = f'std::fma(ctx.f{ra}.f64, ctx.f{frc}.f64, -ctx.f{rb}.f64)'
        return difference if xo == 28 else f'-{difference}'

    @staticmethod
    def condition(bo, bi):
        """The statements before the branch (the count register's decrement) and its condition as C++, None for an
        unconditional branch. The count register is tested on its low word, as in the titles' 32-bit mode."""
        parts, decrement = [], []
        if not bo & 0x4:
            decrement.append('--ctx.ctr.u64;')
            parts.append(f'ctx.ctr.u32 {"==" if bo & 0x2 else "!="} 0')
        if not bo & 0x10:
            bit = f'ctx.cr{bi >> 2}.{CR_BITS[bi & 3]}'
            parts.append(bit if bo & 0x8 else f'!{bit}')
        return decrement, ' && '.join(parts) if parts else None


def decode_function(image, address, count, image_base=IMAGE_BASE):
    start = address - image_base
    words = struct.unpack(f'>{count}I', image[start:start + 4 * count])
    instructions = [Instruction(address + 4 * i, w) for i, w in enumerate(words)]
    for i in instructions:
        if i.word == BCTR:
            table = jump_table(image, image_base, i.address, address)
            if table:
                i.set_table(*table)
    return instructions


def word_at(image, image_base, address):
    start = address - image_base
    if start < 0 or start + 4 > len(image):
        return None
    return struct.unpack('>I', image[start:start + 4])[0]


def unconditional_end(w):
    """b, bl, blr, bctr (and their link forms), sc, tw, twi: where a scan back from a bctr stops."""
    op = w >> 26
    if op in (3, 17, 18):
        return True
    if op == 19 and (w >> 1) & 0x3FF in (16, 528):
        return (w >> 21) & 31 == 20
    return op == 31 and (w >> 1) & 0x3FF == 4


def written_register(w):
    """The register written by an instruction the index can come through, else None."""
    op, xo = w >> 26, (w >> 1) & 0x3FF
    if op == 21:
        return (w >> 16) & 31
    if op in (14, 15, 32, 34, 40):
        return (w >> 21) & 31
    if op == 31 and xo in (24, 28, 316, 444, 536, 792, 824):
        return (w >> 16) & 31
    if op == 31 and (xo in (23, 87, 279) or xo & 0x1FF in (40, 266)):
        return (w >> 21) & 31
    return None


def table_bound(image, image_base, bctr, index):
    """The entry count the bound check of the index register before bctr allows: `cmplwi` / `cmpwi` index,n gives
    n + 1, `clrlwi` index,n gives 2^(32 - n); None when the scan back meets an unconditional branch first."""
    address = bctr
    for _ in range(64):
        address -= 4
        w = word_at(image, image_base, address)
        if w is None or unconditional_end(w):
            return None
        op = w >> 26
        if op in (10, 11) and (w >> 16) & 31 == index:
            return (s16(w & 0xFFFF) + 1) & 0xFFFFFFFF
        if (op == 21 and (w >> 16) & 31 == index and (w >> 11) & 31 == 0 and (w >> 1) & 31 == 31
                and (w >> 6) & 31 > 0):
            return 1 << (32 - ((w >> 6) & 31))
    return None


def jump_table(image, image_base, bctr, function_start):
    """The jump table bctr dispatches through, as (index register, targets), else None (a tail call through ctr).

    The words before bctr, back to the first unconditional branch: the `mtctr` of the target, the `add` of a base and
    an offset and the `rlwinm` that scales the offset (followed to the loaded register), the indexed load (`lwzx`: the
    targets; `lhzx`, `lbzx`: offsets from the base), the `slwi` that scales the index (followed to the index register),
    and the `lis` / `addi` (or `ori`) pairs of the base (between the load and `mtctr`) and of the table (before the
    load). The entries are read up to the bound check's count (table_bound), stopping at the first that is not a
    word-aligned address in the image at or after the function's start; with none, it is a tail call. A table without
    a bound check, or with an entry on a word 0 or 0xFFFFFFFF, raises Unsupported."""
    ctr = index = final = None
    table = base = 0
    pending = {}
    kind, shift, loaded = 'words', 0, False
    address = bctr
    for _ in range(64):
        address -= 4
        w = word_at(image, image_base, address)
        if w is None or unconditional_end(w):
            break
        op, xo = w >> 26, (w >> 1) & 0x3FF
        rt, ra, rb = (w >> 21) & 31, (w >> 16) & 31, (w >> 11) & 31
        if ctr is None:
            if op == 31 and xo == 467 and (ra | (rb << 5)) != 8:
                ctr = rt
            continue
        if not loaded:
            if op == 31 and xo in (23, 87, 279) and rt == ctr:
                if xo == 23:
                    kind = 'words'
                elif kind != 'shifted bytes':
                    kind = 'bytes' if xo == 87 else 'halfwords'
                index = final = rb
                loaded = True
                continue
            if op == 31 and xo & 0x1FF == 266 and rt == ctr:
                ctr = rb if ra == ctr else ra
                continue
            if op == 21 and ra == ctr:
                shift = rb
                if shift:
                    kind = 'shifted bytes'
                ctr = rt
                continue
        if loaded and index is not None and written_register(w) == index:
            if op == 21 and rb > 0 and (w >> 6) & 31 == 0 and (w >> 1) & 31 == 31 - rb:
                index = final = rt
            else:
                index = None
        part = 'table' if loaded else 'base'
        current = table if loaded else base
        value = None
        if op == 15 and ra == 0:
            if current == 0:
                high = (w & 0xFFFF) << 16
                low = pending.pop(part + ' low', None)
                value = high if low is None else join(high, *low)
        elif (op == 14 and ra != 0) or (op == 24 and w != 0x60000000):
            low = (w & 0xFFFF, op == 14)
            if current == 0 and part + ' high' in pending:
                value = join(pending.pop(part + ' high'), *low)
            elif current == 0 and part + ' low' not in pending:
                pending[part + ' low'] = low
            elif current and current & 0xFFFF == 0:
                value = join(current, *low)
        if value is not None:
            if loaded:
                table = value
            else:
                base = value
    if ctr is None or not loaded or table == 0:
        return None
    count = table_bound(image, image_base, bctr, final)
    if kind != 'words' and base == 0:
        raise Unsupported(f'jump table at {bctr:08X} without a base')
    size = {'words': 4, 'halfwords': 2}.get(kind, 1)
    targets = []
    for n in range(512 if count is None else count):
        start = table - image_base + size * n
        if start < 0 or start + size > len(image):
            break
        entry = int.from_bytes(image[start:start + size], 'big')
        target = entry if kind == 'words' else (base + (entry << shift if kind == 'shifted bytes' else entry)) & 0xFFFFFFFF
        if target & 3 or word_at(image, image_base, target) is None or target < function_start:
            break
        if word_at(image, image_base, target) in (0, 0xFFFFFFFF):
            raise Unsupported(f'jump table at {bctr:08X} to {target:08X}, not code')
        targets.append(target)
    if not targets:
        return None
    if count is None:
        raise Unsupported(f'jump table at {bctr:08X} without a bound check')
    return final, targets


def join(high, low, added):
    return (high + s16(low)) & 0xFFFFFFFF if added else high | low


HELPERS = (
    # name, opcode of each word, base register, offset of register n, the words after r31 / f31
    ('SaveGprLr', 62, 1, lambda n: -(8 * (32 - n) + 8), (0x9181FFF8, 0x4E800020)),
    ('RestGprLr', 58, 1, lambda n: -(8 * (32 - n) + 8), (0x8181FFF8, 0x7D8803A6, 0x4E800020)),
    ('SaveFpr', 54, 12, lambda n: -8 * (32 - n), (0x4E800020,)),
    ('RestFpr', 50, 12, lambda n: -8 * (32 - n), (0x4E800020,)),
)


def find_helper(image, address):
    """The PowerPC ABI's register save or restore helper entered at address, as (name, first register), else None:
    __savegprlr_n / __restgprlr_n store or load r_n..r31 below r1 and lr (through r12) at r1 - 8, __savefpr_n /
    __restfpr_n f_n..f31 below r12."""
    start = address - IMAGE_BASE
    if start < 0 or start + 4 > len(image):
        return None
    first = struct.unpack('>I', image[start:start + 4])[0]
    for name, op, base, offset, tail in HELPERS:
        n = (first >> 21) & 31
        if first >> 26 != op or n < 14:
            continue
        expected = [(op << 26) | (r << 21) | (base << 16) | (offset(r) & 0xFFFF) for r in range(n, 32)] + list(tail)
        words = struct.unpack(f'>{len(expected)}I', image[start:start + 4 * len(expected)])
        if list(words) == expected:
            return name, n
    return None


def import_libraries(xex):
    """The names of the libraries an XEX2 file imports from (its import libraries header, 0x000103FF), in the order its
    import records number them, without their extension: ('xboxkrnl', 'xam')."""
    data = Path(xex).read_bytes()
    if data[:4] != b'XEX2':
        raise SystemExit(f'ppc_translate: {xex}: not an XEX2 file')
    count = struct.unpack_from('>I', data, 0x14)[0]
    headers = dict(struct.unpack_from('>II', data, 0x18 + 8 * i) for i in range(count))
    at = headers.get(0x000103FF)
    if at is None:
        return ()
    _, strings, libraries = struct.unpack_from('>III', data, at)
    names = [n.decode('ascii').rsplit('.', 1)[0] for n in data[at + 12:at + 12 + strings].split(b'\0') if n]
    order, offset = [], at + 12 + strings
    for _ in range(libraries):
        size = struct.unpack_from('>I', data, offset)[0]
        order.append(names[struct.unpack_from('>H', data, offset + 36)[0]])
        offset += size
    return tuple(order)


def find_import(image, address, libraries):
    """The import whose thunk is at address, as (library, ordinal), else None: the XEX loader's words
    0x01LLOOOO 0x02LLOOOO (library LL of libraries, ordinal OOOO), then mtctr r11; bctr."""
    start = address - IMAGE_BASE
    if not libraries or start < 0 or start + 16 > len(image):
        return None
    first, second, mtctr, bctr = struct.unpack('>4I', image[start:start + 16])
    if (mtctr, bctr) != (0x7D6903A6, 0x4E800420) or first >> 24 != 1 or second != first + 0x01000000:
        return None
    library = (first >> 16) & 0xFF
    return (libraries[library], first & 0xFFFF) if library < len(libraries) else None


def tail_calls(instructions, end, starts, helpers=None, imports=None):
    """The branches (not calls) of a function to another function's start: inside the function's range only when a
    function starts there, a branch to its own start being a loop."""
    begin = instructions[0].address
    tails = []
    for i in instructions:
        if i.target is None or i.call or i.target == begin:
            continue
        if i.target in starts or (helpers and i.target in helpers) or (imports and i.target in imports):
            tails.append(i)
        elif not begin <= i.target < end:
            raise Unsupported(f'branch out of the function to {i.target:08X}, not a function start')
    return tails


def import_call(imported):
    return f'ANY360_CPU_CALL_IMPORT(ctx, base, {imported[0]}, {imported[1]})'


def function_body(name, instructions, end, starts=frozenset(), helpers=None, imports=None):
    helpers, imports = helpers or {}, imports or {}
    tails = tail_calls(instructions, end, starts, helpers, imports)
    for i in tails:
        callee = (f'{helpers[i.target][0]}(ctx, base, {helpers[i.target][1]})' if i.target in helpers
                  else import_call(imports[i.target]) if i.target in imports
                  else f'sub_{i.target:08X}(ctx, base)')
        i.code = [c.replace(f'goto loc_{i.target:08X};', f'{{ {callee}; return; }}') for c in i.code]
    for i in instructions:
        if i.call and i.target in helpers:
            i.code = [c.replace(f'sub_{i.target:08X}(ctx, base)', f'{helpers[i.target][0]}(ctx, base, {helpers[i.target][1]})')
                      for c in i.code]
        elif i.call and i.target in imports:
            i.code = [c.replace(f'sub_{i.target:08X}(ctx, base)', import_call(imports[i.target])) for c in i.code]
    targets = {i.target for i in instructions if i.target is not None and not i.call and i not in tails}
    begin = instructions[0].address
    for i in instructions:
        for target in i.table or ():
            if not begin <= target < end or target & 3 or (target != begin and target in starts):
                raise Unsupported(f'jump table at {i.address:08X} to {target:08X}, not a label of the function')
            targets.add(target)
    if not instructions[-1].ends:
        raise Unsupported('falls off its end')
    lines = [f'inline void {name}(Ctx& ctx, const Memory& base) {{']
    if any('ea =' in c for i in instructions for c in i.code):
        lines.append('  uint32_t ea;')
    flush_off = False
    for i in instructions:
        if i.address in targets:
            lines.append(f'loc_{i.address:08X}:')
            flush_off = False
        if i.fpu and not flush_off:
            lines.append('  ctx.fpscr.disableFlushMode();')
            flush_off = True
        lines += [f'  {c}' for c in i.code]
        if i.call or i.indirect:
            flush_off = False
    lines.append('}')
    return lines


_next_starts = {}


def extent(image, sizes, instructions, end):
    """Where the function ends once the case blocks its jump tables reach past its listed end are taken in: from the
    last such target to the first unconditional branch, the function then ending there; never past the next listed
    function's start."""
    beyond = [t for i in instructions for t in i.table or () if t >= end]
    if not beyond:
        return end
    starts = _next_starts.get(id(sizes))
    if starts is None or starts[0] is not sizes:
        starts = _next_starts[id(sizes)] = (sizes, sorted(sizes))
    n = bisect.bisect_right(starts[1], instructions[0].address)
    following = starts[1][n] if n < len(starts[1]) else 1 << 32
    address = max(beyond)
    while address < following:
        w = word_at(image, IMAGE_BASE, address)
        if w is None:
            break
        if w >> 26 in (18, 19) and not w & 1 and unconditional_end(w):
            return address + 4
        address += 4
    raise Unsupported(f'jump table to {max(beyond):08X}, past the function and with no end before the next one')


def translate_tree(image, sizes, root, done, order, leaves, libraries=()):
    if root in done:
        return
    if root not in sizes:
        raise Unsupported(f'call to {root:08X}, not a known function')
    instructions = decode_function(image, root, sizes[root])
    end = root + 4 * sizes[root]
    stretched = extent(image, sizes, instructions, end)
    if stretched != end:
        end = stretched
        instructions = decode_function(image, root, (end - root) // 4)
    helpers = {i.target: h for i in instructions if i.target is not None and (h := find_helper(image, i.target))}
    imports = {i.target: m for i in instructions
               if i.target is not None and i.target not in sizes and (m := find_import(image, i.target, libraries))}
    callees = [i.target for i in instructions if i.call] + [
        i.target for i in tail_calls(instructions, end, sizes, helpers, imports)]
    callees = [c for c in callees if c not in helpers and c not in imports]
    if leaves and callees:
        raise Unsupported('not a leaf')
    done.add(root)
    try:
        for callee in callees:
            translate_tree(image, sizes, callee, done, order, leaves, libraries)
        body = function_body(f'sub_{root:08X}', instructions, end, sizes, helpers, imports)
    except Unsupported:
        done.discard(root)
        raise
    order.append((root, body))


def header(source, what, namespace, bodies):
    out = [HEADER.format(source=source, what=what, namespace=namespace)]
    names = [name for name, _ in bodies]
    out += [f'inline void {n}(Ctx& ctx, const Memory& base);' for n in names]
    out.append('')
    for _, body in bodies:
        out += body + ['']
    out.append(f'}}  // namespace {namespace}')
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--image', type=Path)
    parser.add_argument('--xex', type=Path, help="the title's XEX: its import libraries name the calls to imports")
    parser.add_argument('--functions', type=Path)
    parser.add_argument('--cases', type=Path)
    parser.add_argument('--namespace', required=True)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--root', action='append', default=[])
    parser.add_argument('--pick', type=int, default=0)
    parser.add_argument('--min', type=int, default=8)
    parser.add_argument('--leaves', action='store_true')
    parser.add_argument('--list', type=Path, help='writes the picked roots, one hex address a line')
    args = parser.parse_args()

    if args.cases:
        text = args.cases.read_text(encoding='utf-8')
        tested = {item.split()[0].rstrip('.+-') for line in text.splitlines() if line.startswith('# ')
                  for item in line[2:].split(';') if item.strip()}
        untested = [m for m in COVERED_MNEMONICS if m not in tested]
        if untested:
            raise SystemExit(f'ppc_translate: covered but in no case of {args.cases.name}: {", ".join(untested)}')
        lines = [line.split('#', 1)[0].strip() for line in text.splitlines()]
        data = [(int(line[1:].split()[0], 16), [int(h, 16) for h in line.split()[1:]]) for line in lines
                if line.startswith('@')]
        imports = {int(line.split()[1], 16): (line.split()[2], int(line.split()[3])) for line in lines
                   if line.split()[:1] == ['import']}
        bodies = []
        for line in lines:
            if not line or line.startswith('@') or line.split()[0] == 'import':
                continue
            name, *hex_words = line.split()
            words = [int(h, 16) for h in hex_words]
            memory = bytearray(struct.pack(f'>{len(words)}I', *words))
            for address, values in data:
                start = address - 0x10000
                memory.extend(bytes(max(0, start + 4 * len(values) - len(memory))))
                memory[start:start + 4 * len(values)] = struct.pack(f'>{len(values)}I', *values)
            instructions = decode_function(bytes(memory), 0x10000, len(words), 0x10000)
            if any(i.call and i.target != 0x10000 and i.target not in imports for i in instructions):
                raise SystemExit(f'ppc_translate: case {name} calls another address than its own start or an import')
            body = function_body(name, instructions, 0x10000 + 4 * len(instructions), imports=imports)
            bodies.append((name, [line.replace('sub_00010000(', f'{name}(') for line in body]))
        if any(len(values) > 16 for _, values in data):
            raise SystemExit(f'ppc_translate: a data line of {args.cases.name} has more than 16 words')
        rows = ''.join(f'    {{0x{address:X}u, {len(values)}u, {{{", ".join(f"0x{v:08X}u" for v in values)}}}}},\n'
                       for address, values in data)
        case_data = ('struct CaseData {\n  uint32_t address, count;\n  uint32_t words[16];\n};\n'
                     f'inline constexpr CaseData kCaseData[] = {{\n{rows}}};\n\n')
        text = header(args.cases.name, 'the instruction test cases', args.namespace, bodies)
        text = text.replace(f'}}  // namespace {args.namespace}', case_data + f'}}  // namespace {args.namespace}')
        args.out.write_text(text, encoding='utf-8')
        print(f'ppc_translate: {len(bodies)} cases')
        return

    image = args.image.read_bytes()
    table = json.loads(args.functions.read_text(encoding='utf-8'))
    sizes = {int(r[0], 16): int(r[1]) for r in table['rows']}
    libraries = import_libraries(args.xex) if args.xex else ()
    done, order = set(), []
    roots = [int(r, 16) for r in args.root]
    if args.pick:
        picked = []
        for address in sorted(sizes):
            if sizes[address] < args.min:
                continue
            try:
                translate_tree(image, sizes, address, done, order, args.leaves, libraries)
                picked.append(address)
            except Unsupported:
                continue
            if len(picked) == args.pick:
                break
        roots = picked
    else:
        for root in roots:
            translate_tree(image, sizes, root, done, order, args.leaves, libraries)
    bodies = [(f'sub_{a:08X}', body) for a, body in order]
    what = f'{len(roots)} roots, {len(bodies)} functions'
    args.out.write_text(header(f'{args.image.name} ({table.get("name", "")})', what, args.namespace, bodies),
                        encoding='utf-8')
    if args.list:
        args.list.write_text(''.join(f'{r:08X}\n' for r in roots), encoding='utf-8')
    print(f'ppc_translate: {what}')


if __name__ == '__main__':
    main()
