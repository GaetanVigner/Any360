#!/usr/bin/env python3
"""Any360's PowerPC translator: a title's functions, read from the PowerPC words of its XEX image, as C++.

Each function becomes `inline void sub_<address>(Ctx& ctx, const Memory& base)` on any360/xdk/ppc_model.h's context and
guest memory: one statement block per instruction, a label where a branch lands, the callees taken along. The
instructions covered (docs/CPU.md lists them with their encodings) are the most used ones of the known titles
(docs/ROADMAP.md); a function with any other instruction, an indirect branch, a branch out of the function that is not
a call, or a call to a function that cannot be translated, is left out.

  python -I tools/ppc_translate.py --image <default_image.bin> --functions <functions-<title>.json> \\
      --namespace <ns> --out <header> (--root <address>... | --pick <count> [--min <instructions>] [--leaves])
  python -I tools/ppc_translate.py --cases <cases.txt> --namespace <ns> --out <header>

A cases file has one function a line: `<name> <hex word> <hex word> ...` (the words of a function that ends in blr),
for the instruction tests.
"""
import argparse
import json
import re
import struct
from pathlib import Path

IMAGE_BASE = 0x82000000

# The mnemonics (as the recompiled code's comments name them, without a branch hint or a record dot) whose encodings
# Instruction.decode translates. Each one is in a case of the instruction tests (--cases checks it).
COVERED_MNEMONICS = (
    'li', 'addi', 'lis', 'addis', 'lwz', 'stw', 'stwu', 'ld', 'std', 'lfs', 'stfs', 'fmuls',
    'cmpw', 'cmplw', 'cmpd', 'cmpld', 'cmpwi', 'cmplwi', 'cmpdi', 'cmpldi', 'rlwinm', 'clrlwi', 'rotlwi',
    'or', 'mr', 'add', 'mflr', 'mtlr', 'mfctr', 'mtctr', 'b', 'bl', 'blr',
    'blt', 'bgt', 'beq', 'bso', 'bge', 'ble', 'bne', 'bns', 'beqlr', 'bnelr', 'bltlr', 'bgelr', 'bgtlr', 'blelr',
    'bdnz', 'bdz', 'bdnzf', 'bdnzt', 'bdzf', 'bdzlr')
COVERED = re.compile(r'(%s)[+-]?\.?' % '|'.join(COVERED_MNEMONICS))

HEADER = '''// Generated by tools/ppc_translate.py from {source}: {what}.
// Do not edit by hand; run the tool again.
#pragma once

#include <bit>
#include <cstdint>

#include "any360/xdk/ppc_model.h"

namespace {namespace} {{

using any360::xdk::Memory;
using any360::xdk::ppc_model::Ctx;
using any360::xdk::ppc_model::Load32;
using any360::xdk::ppc_model::Load64;
using any360::xdk::ppc_model::Store32;
using any360::xdk::ppc_model::Store64;

'''


class Unsupported(Exception):
    pass


def s16(v):
    return v - 0x10000 if v & 0x8000 else v


def s14(v):
    v &= 0xFFFC
    return v - 0x10000 if v & 0x8000 else v


def s26(v):
    v &= 0x3FFFFFC
    return v - 0x4000000 if v & 0x2000000 else v


def mask64(mb, me):
    """The PowerPC mask of bits mb..me (bit 0 the most significant of 64), wrapping when mb > me."""
    def ones_from(b):
        return (1 << (64 - b)) - 1
    if mb <= me:
        return ones_from(mb) & ~ones_from(me + 1) & 0xFFFFFFFFFFFFFFFF
    return (ones_from(mb) | (~ones_from(me + 1) & 0xFFFFFFFFFFFFFFFF)) & 0xFFFFFFFFFFFFFFFF


CR_BITS = ('lt', 'gt', 'eq', 'so')


def ea(ra, d):
    return f'{d}u' if ra == 0 else f'ctx.r{ra}.u32 + {d}u' if d >= 0 else f'ctx.r{ra}.u32 - {-d}u'


def cr0(reg):
    return f'ctx.cr0.compare<int32_t>(ctx.r{reg}.s32, 0, ctx.xer);'


class Instruction:
    def __init__(self, address, word):
        self.address, self.word = address, word
        self.target = None      # a branch's target inside or outside the function
        self.call = False       # bl
        self.ends = False       # blr, b, or a branch with no fall-through
        self.fpu = False        # a floating-point instruction that runs with the flush mode off
        self.code = self.decode()

    def decode(self):
        w, a = self.word, self.address
        op = w >> 26
        rd, ra, rb = (w >> 21) & 31, (w >> 16) & 31, (w >> 11) & 31
        imm = w & 0xFFFF
        rc = w & 1
        if op == 14:
            return [f'ctx.r{rd}.s64 = {s16(imm)};' if ra == 0 else f'ctx.r{rd}.s64 = ctx.r{ra}.s64 + {s16(imm)};']
        if op == 15:
            shifted = s16(imm) << 16
            return [f'ctx.r{rd}.s64 = {shifted}ll;' if ra == 0 else f'ctx.r{rd}.s64 = ctx.r{ra}.s64 + {shifted}ll;']
        if op == 32:
            return [f'ctx.r{rd}.u64 = Load32(base, {ea(ra, s16(imm))});']
        if op == 36:
            return [f'Store32(base, {ea(ra, s16(imm))}, ctx.r{rd}.u32);']
        if op == 37:
            if ra == 0:
                raise Unsupported('stwu with rA 0')
            return [f'ea = {ea(ra, s16(imm))};', f'Store32(base, ea, ctx.r{rd}.u32);', f'ctx.r{ra}.u32 = ea;']
        if op == 58 and w & 3 == 0:
            return [f'ctx.r{rd}.u64 = Load64(base, {ea(ra, s14(imm))});']
        if op == 62 and w & 3 == 0:
            return [f'Store64(base, {ea(ra, s14(imm))}, ctx.r{rd}.u64);']
        if op == 48:
            self.fpu = True
            return [f'ctx.f{rd}.f64 = double(std::bit_cast<float>(Load32(base, {ea(ra, s16(imm))})));']
        if op == 52:
            return [f'Store32(base, {ea(ra, s16(imm))}, std::bit_cast<uint32_t>(float(ctx.f{rd}.f64)));']
        if op == 59 and (w >> 1) & 31 == 25 and not rc and rb == 0:
            frc = (w >> 6) & 31
            self.fpu = True
            return [f'ctx.f{rd}.f64 = double(float(ctx.f{ra}.f64 * ctx.f{frc}.f64));']
        if op in (10, 11):
            crf, wide = (w >> 23) & 7, (w >> 21) & 1
            if op == 11:
                t, v, k = ('int64_t', f'ctx.r{ra}.s64', s16(imm)) if wide else ('int32_t', f'ctx.r{ra}.s32', s16(imm))
            else:
                t, v, k = ('uint64_t', f'ctx.r{ra}.u64', imm) if wide else ('uint32_t', f'ctx.r{ra}.u32', imm)
            return [f'ctx.cr{crf}.compare<{t}>({v}, {k}, ctx.xer);']
        if op == 21:
            sh, mb, me = rb, (w >> 6) & 31, (w >> 1) & 31
            m = mask64(mb + 32, me + 32)
            rot = (f'std::rotl(uint64_t(ctx.r{rd}.u32) | (uint64_t(ctx.r{rd}.u32) << 32), {sh})' if sh
                   else f'(uint64_t(ctx.r{rd}.u32) | (uint64_t(ctx.r{rd}.u32) << 32))')
            return [f'ctx.r{ra}.u64 = {rot} & 0x{m:X}ull;'] + ([cr0(ra)] if rc else [])
        if op == 31:
            xo = (w >> 1) & 0x3FF
            if xo in (0, 32):
                crf, wide = (w >> 23) & 7, (w >> 21) & 1
                kind = 's' if xo == 0 else 'u'
                t = {('s', 0): 'int32_t', ('s', 1): 'int64_t', ('u', 0): 'uint32_t', ('u', 1): 'uint64_t'}[(kind, wide)]
                field = f'{kind}{64 if wide else 32}'
                return [f'ctx.cr{crf}.compare<{t}>(ctx.r{ra}.{field}, ctx.r{rb}.{field}, ctx.xer);']
            if xo == 444:
                value = f'ctx.r{rd}.u64' if rd == rb else f'ctx.r{rd}.u64 | ctx.r{rb}.u64'
                return [f'ctx.r{ra}.u64 = {value};'] + ([cr0(ra)] if rc else [])
            if xo == 266 and not (w >> 10) & 1:
                return [f'ctx.r{rd}.u64 = ctx.r{ra}.u64 + ctx.r{rb}.u64;'] + ([cr0(rd)] if rc else [])
            if xo in (339, 467):
                spr = ((w >> 16) & 31) | (((w >> 11) & 31) << 5)
                name = {8: 'lr', 9: 'ctr'}.get(spr)
                if not name:
                    raise Unsupported(f'spr {spr}')
                register = 'ctx.lr' if name == 'lr' else 'ctx.ctr.u64'
                return [f'ctx.r{rd}.u64 = {register};' if xo == 339 else f'{register} = ctx.r{rd}.u64;']
            raise Unsupported(f'opcode 31 xo {xo}')
        if op == 18:
            target = (s26(w) if w & 2 else a + s26(w)) & 0xFFFFFFFF
            self.target = target
            if w & 1:
                self.call = True
                return [f'ctx.lr = 0x{a + 4:X};', f'sub_{target:08X}(ctx, base);']
            self.ends = True
            return [f'goto loc_{target:08X};']
        if op == 16:
            bo, bi = rd, ra
            if w & 3:
                raise Unsupported('bc with link or absolute')
            target = (a + s14(w)) & 0xFFFFFFFF
            self.target = target
            decrement, condition = self.condition(bo, bi)
            if condition is None:
                self.ends = True
                return [f'goto loc_{target:08X};']
            return decrement + [f'if ({condition}) goto loc_{target:08X};']
        if op == 19 and (w >> 1) & 0x3FF == 16 and not w & 1:
            decrement, condition = self.condition(rd, ra)
            if condition is None:
                self.ends = True
                return ['return;']
            return decrement + [f'if ({condition}) return;']
        raise Unsupported(f'opcode {op}')

    @staticmethod
    def condition(bo, bi):
        """The statements before the branch (the count register's decrement) and its condition as C++, None for an
        unconditional branch. The count register is tested on its low word, as in the titles' 32-bit mode."""
        parts, decrement = [], []
        if not bo & 0x4:
            decrement.append('--ctx.ctr.u64;')
            parts.append(f'ctx.ctr.u32 {"==" if bo & 0x2 else "!="} 0')
        if not bo & 0x10:
            bit = f'ctx.cr{bi >> 2}.{CR_BITS[bi & 3]}'
            parts.append(bit if bo & 0x8 else f'!{bit}')
        return decrement, ' && '.join(parts) if parts else None


def decode_function(image, address, count):
    start = address - IMAGE_BASE
    words = struct.unpack(f'>{count}I', image[start:start + 4 * count])
    return [Instruction(address + 4 * i, w) for i, w in enumerate(words)]


def function_body(name, instructions, end):
    targets = {i.target for i in instructions if i.target is not None and not i.call}
    begin = instructions[0].address
    for i in instructions:
        if i.target is not None and not i.call and not (begin <= i.target < end):
            raise Unsupported(f'branch out of the function to {i.target:08X}')
    if not instructions[-1].ends:
        raise Unsupported('falls off its end')
    lines = [f'inline void {name}(Ctx& ctx, const Memory& base) {{']
    if any('ea =' in c for i in instructions for c in i.code):
        lines.append('  uint32_t ea;')
    flush_off = False
    for i in instructions:
        if i.address in targets:
            lines.append(f'loc_{i.address:08X}:')
            flush_off = False
        if i.fpu and not flush_off:
            lines.append('  ctx.fpscr.disableFlushMode();')
            flush_off = True
        lines += [f'  {c}' for c in i.code]
        if i.call:
            flush_off = False
    lines.append('}')
    return lines


def translate_tree(image, sizes, root, done, order, leaves):
    if root in done:
        return
    if root not in sizes:
        raise Unsupported(f'call to {root:08X}, not a known function')
    instructions = decode_function(image, root, sizes[root])
    callees = [i.target for i in instructions if i.call]
    if leaves and callees:
        raise Unsupported('not a leaf')
    done.add(root)
    try:
        for callee in callees:
            translate_tree(image, sizes, callee, done, order, leaves)
        body = function_body(f'sub_{root:08X}', instructions, root + 4 * sizes[root])
    except Unsupported:
        done.discard(root)
        raise
    order.append((root, body))


def header(source, what, namespace, bodies):
    out = [HEADER.format(source=source, what=what, namespace=namespace)]
    names = [name for name, _ in bodies]
    out += [f'inline void {n}(Ctx& ctx, const Memory& base);' for n in names]
    out.append('')
    for _, body in bodies:
        out += body + ['']
    out.append(f'}}  // namespace {namespace}')
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--image', type=Path)
    parser.add_argument('--functions', type=Path)
    parser.add_argument('--cases', type=Path)
    parser.add_argument('--namespace', required=True)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--root', action='append', default=[])
    parser.add_argument('--pick', type=int, default=0)
    parser.add_argument('--min', type=int, default=8)
    parser.add_argument('--leaves', action='store_true')
    parser.add_argument('--list', type=Path, help='writes the picked roots, one hex address a line')
    args = parser.parse_args()

    if args.cases:
        text = args.cases.read_text(encoding='utf-8')
        tested = {item.split()[0].rstrip('.+-') for line in text.splitlines() if line.startswith('# ')
                  for item in line[2:].split(';') if item.strip()}
        untested = [m for m in COVERED_MNEMONICS if m not in tested]
        if untested:
            raise SystemExit(f'ppc_translate: covered but in no case of {args.cases.name}: {", ".join(untested)}')
        bodies = []
        for line in text.splitlines():
            line = line.split('#', 1)[0].strip()
            if not line:
                continue
            name, *hex_words = line.split()
            instructions = [Instruction(0x10000 + 4 * i, int(h, 16)) for i, h in enumerate(hex_words)]
            if any(i.call and i.target != 0x10000 for i in instructions):
                raise SystemExit(f'ppc_translate: case {name} calls another address than its own start')
            body = function_body(name, instructions, 0x10000 + 4 * len(instructions))
            bodies.append((name, [line.replace('sub_00010000(', f'{name}(') for line in body]))
        args.out.write_text(header(args.cases.name, 'the instruction test cases', args.namespace, bodies), encoding='utf-8')
        print(f'ppc_translate: {len(bodies)} cases')
        return

    image = args.image.read_bytes()
    table = json.loads(args.functions.read_text(encoding='utf-8'))
    sizes = {int(r[0], 16): int(r[1]) for r in table['rows']}
    done, order = set(), []
    roots = [int(r, 16) for r in args.root]
    if args.pick:
        picked = []
        for address in sorted(sizes):
            if sizes[address] < args.min:
                continue
            try:
                translate_tree(image, sizes, address, done, order, args.leaves)
                picked.append(address)
            except Unsupported:
                continue
            if len(picked) == args.pick:
                break
        roots = picked
    else:
        for root in roots:
            translate_tree(image, sizes, root, done, order, args.leaves)
    bodies = [(f'sub_{a:08X}', body) for a, body in order]
    what = f'{len(roots)} roots, {len(bodies)} functions'
    args.out.write_text(header(f'{args.image.name} ({table.get("name", "")})', what, args.namespace, bodies),
                        encoding='utf-8')
    if args.list:
        args.list.write_text(''.join(f'{r:08X}\n' for r in roots), encoding='utf-8')
    print(f'ppc_translate: {what}')


if __name__ == '__main__':
    main()
